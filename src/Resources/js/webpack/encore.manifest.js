import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { objectMergeDeep } from '@wexample/js-helpers/Helper/Object';
import { stringToKebabCase } from '@wexample/js-helpers/Helper/String';
import { COLORS, logTitle, logEntry, logPath } from '@wexample/js-helpers/Helper/Log';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));

const Encore = require('@symfony/webpack-encore');
const webpack = require('webpack');
const FosRouting = require('fos-router/webpack/FosRouting');
const VirtualModules = require('webpack-virtual-modules');

const DEFAULT_OUTPUT_PATH = 'public/build/';
const DEFAULT_PUBLIC_PATH = '/build';
const DEFAULT_MANIFEST_PATH = path.resolve(process.cwd(), 'assets', 'encore.manifest.json');
const WRAPPER_VIRTUAL_ROOT = path.resolve(process.cwd(), '.encore', 'virtual', 'wrappers');
const WRAPPER_TEMPLATE_PATH = path.resolve(__dirname, 'templates', 'wrapper.js.tpl');

let virtualModulesInstance = null;
let pendingVirtualModules = {};
let wrapperTemplateContent = null;

function maybeGenerateEncoreManifest(options = {}) {
  if (options.generateEncoreManifest === false) {
    return;
  }

  const consolePath = path.resolve(process.cwd(), 'bin', 'console');
  if (!fs.existsSync(consolePath)) {
    return;
  }

  execSync(
    options.generateEncoreManifestCommand || 'php bin/console loader:generate-encore-manifest',
    {stdio: 'inherit'}
  );
}

function configureEncoreBase(options = {}) {
  const env = options.env || process.env.NODE_ENV || 'dev';

  if (!Encore.isRuntimeEnvironmentConfigured()) {
    Encore.configureRuntimeEnvironment(env);
  }

  const isProd = Encore.isProduction();
  const loaderConfig = objectMergeDeep({
    sass: {
      additionalData: null,
      sassOptions: {
        quietDeps: true,
      },
    },
    css: {
      modules: false,
      esModule: true,
    },
    postcss: {
      enabled: true,
      postcssOptions: null,
    },
    vue: {
      runtimeCompilerBuild: true,
      loaderOptions: {},
    },
    ts: {
      onlyCompileBundledFiles: true,
      transpileOnly: false,
      configFile: undefined,
      compilerOptions: {},
    },
  }, options.loaders || {});

  // Allow Symfony-side config to drive the TS config file (generated by loader:generate-encore-manifest)
  if (!loaderConfig.ts.configFile && fs.existsSync(DEFAULT_MANIFEST_PATH)) {
    try {
      const loaderRuntimeConfig = JSON.parse(fs.readFileSync(DEFAULT_MANIFEST_PATH, 'utf8'));
      if (loaderRuntimeConfig && typeof loaderRuntimeConfig.tsconfigPath === 'string' && loaderRuntimeConfig.tsconfigPath.length) {
        loaderConfig.ts.configFile = loaderRuntimeConfig.tsconfigPath;
      }
    } catch (e) {
      // Ignore invalid manifest file and keep default tsconfig resolution.
    }
  }

  if (options.dumpFosRoutes !== false) {
    execSync(
      options.fosCommand ||
        'php bin/console fos:js-routing:dump --format=json --target=var/cache/fosRoutes.json',
      {stdio: 'inherit'}
    );
  }

  Encore
    .setOutputPath(options.outputPath || DEFAULT_OUTPUT_PATH)
    .setPublicPath(options.publicPath || DEFAULT_PUBLIC_PATH)
    .enableSingleRuntimeChunk()
    .cleanupOutputBeforeBuild()
    .enableBuildNotifications()
    .enableSourceMaps(options.sourceMaps ?? !isProd)
    .enableVersioning(options.versioning ?? isProd)
    .addPlugin(new webpack.DefinePlugin({
      __VUE_OPTIONS_API__: true,
      __VUE_PROD_DEVTOOLS__: false,
      __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: false,
    }))
    .addPlugin(new FosRouting())
    .enableSassLoader((loaderOptions) => {
      const additionalData = loaderConfig.sass.additionalData;

      if (additionalData) {
        if (typeof additionalData === 'function') {
          loaderOptions.additionalData = additionalData(loaderOptions.additionalData || '');
        } else {
          loaderOptions.additionalData = `${additionalData}\n${loaderOptions.additionalData || ''}`.trim();
        }
      }

      loaderOptions.sassOptions = objectMergeDeep(
        loaderOptions.sassOptions || {},
        loaderConfig.sass.sassOptions || {}
      );
    })
    .enableTypeScriptLoader((tsOptions) => {
      tsOptions.onlyCompileBundledFiles = loaderConfig.ts.onlyCompileBundledFiles !== false;
      tsOptions.transpileOnly = loaderConfig.ts.transpileOnly === true;

      const compilerOptions = objectMergeDeep({}, loaderConfig.ts.compilerOptions || {});

      if (!isProd && options.enableTsSourceMaps !== false) {
        compilerOptions.sourceMap = true;
      }

      tsOptions.compilerOptions = compilerOptions;

      if (loaderConfig.ts.configFile) {
        tsOptions.configFile = loaderConfig.ts.configFile;
      }
    })
    .enableIntegrityHashes(options.integrity ?? isProd);

  Encore.configureCssLoader((cssOptions) => {
    cssOptions.esModule = loaderConfig.css.esModule !== false;
    cssOptions.modules = loaderConfig.css.modules || false;
  });

  if (loaderConfig.postcss.enabled !== false) {
    Encore.enablePostCssLoader((postCssOptions) => {
      if (loaderConfig.postcss.postcssOptions) {
        postCssOptions.postcssOptions = loaderConfig.postcss.postcssOptions;
      }
    });
  }

  Encore.enableVueLoader(
    (vueLoaderOptions) => {
      Object.assign(vueLoaderOptions, loaderConfig.vue.loaderOptions || {});
    },
    {
      runtimeCompilerBuild: loaderConfig.vue.runtimeCompilerBuild !== false,
    }
  );

  Encore.configureWatchOptions((watchOptions) => {
    watchOptions.aggregateTimeout = watchOptions.aggregateTimeout ?? 200;
    watchOptions.poll = watchOptions.poll ?? false;
    // Keep watching vendor/<bundle>/assets (symlinked packages hot-reload),
    // but skip their internal trees: a single package's own composer vendor
    // can hold ~1k directories, and watching them across every front
    // exhausts inotify handles (EMFILE).
    watchOptions.ignored = watchOptions.ignored ?? [
      '**/node_modules/**',
      '**/vendor/**/vendor/**',
      '**/vendor/**/tests/**',
      '**/.wex/**',
      '**/.git/**',
      '**/var/**',
    ];
  });

  if (typeof options.configureEncore === 'function') {
    options.configureEncore(Encore);
  }

  logTitle(`Encore base configured (${isProd ? 'prod' : 'dev'})`);

  return Encore;
}

function applyManifestEntries(options = {}) {
  const manifestPath = path.resolve(
    process.cwd(),
    options.manifestPath || DEFAULT_MANIFEST_PATH
  );
  const manifest = options.manifest || loadManifest(manifestPath);
  const encore = options.encore || Encore;
  const seenEntries = new Set();

  logTitle(`Manifest ${path.relative(process.cwd(), manifestPath)}`);
  logPath('  Version', `${manifest.version || '?'}`);
  logPath('  Fronts ', `${manifest.frontCount ?? manifest.fronts?.length ?? 0}`);
  logFronts(manifest.fronts || []);

  addAliasesFromManifest(manifest, encore);
  registerCssEntries(manifest, encore, seenEntries);
  registerJsEntries(manifest, encore, seenEntries, options);
  finalizeVirtualModules(encore);

  return manifest;
}

function logFronts(fronts) {
  if (!fronts.length) {
    return;
  }

  logTitle('Front paths', COLORS.yellow);
  fronts.forEach((front) => {
    const label = `${front.bundle} (${front.key})`;
    const rel = front.paths?.relative || front.paths?.absolute || '';
    logPath(`  ${label}`, rel);
  });
}

function loadManifest(filePath = DEFAULT_MANIFEST_PATH) {
  if (!fs.existsSync(filePath)) {
    throw new Error(
      `[encore-manifest] Missing manifest at ${filePath}. ` +
      'Run "php bin/console loader:generate-encore-manifest" first.'
    );
  }

  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function addAliasesFromManifest(manifest, encore) {
  const aliases = manifest.aliases || {};
  const jsDevAliases = manifest.jsDevAliases || {};
  const resolvedAliases = {};

  // Add regular aliases (relative paths)
  Object.entries(aliases).forEach(([alias, relPath]) => {
    resolvedAliases[alias] = path.resolve(process.cwd(), relPath);
  });

  // Add JS dev packages aliases (absolute paths)
  Object.entries(jsDevAliases).forEach(([alias, absPath]) => {
    resolvedAliases[alias] = absPath;
  });

  const aliasesCount = Object.keys(resolvedAliases).length;
  const jsDevCount = Object.keys(jsDevAliases).length;

  if (aliasesCount) {
    logTitle(`Aliases (${aliasesCount}${jsDevCount ? `, ${jsDevCount} dev` : ''})`, COLORS.blue);
    encore.addAliases(resolvedAliases);
    Object.entries(resolvedAliases).forEach(([alias, target]) => {
      logPath(`  ${alias}`, target);
    });
  }
}

function registerCssEntries(manifest, encore, seenEntries) {
  const cssEntries = manifest.entries?.css || [];

  if (cssEntries.length) {
    logTitle(`CSS entries (${cssEntries.length})`, COLORS.magenta);
  }

  cssEntries.forEach((entry) => {
    if (seenEntries.has(entry.output)) {
      return;
    }

    encore.addStyleEntry(
      entry.output,
      resolveSourcePath(entry.source)
    );
    seenEntries.add(entry.output);
    logEntry('style', entry);
  });
}

function registerJsEntries(manifest, encore, seenEntries, options) {
  const jsEntries = manifest.entries?.js || {};

  const categories = Object.keys(jsEntries);
  if (categories.length) {
    logTitle('JS entries', COLORS.magenta);
  }

  Object.values(jsEntries).forEach((categoryEntries) => {
    (categoryEntries || []).forEach((entry) => {
      if (seenEntries.has(entry.output)) {
        return;
      }

      let entrySource = resolveSourcePath(entry.source);

      if (entry.wrapper) {
        entrySource = buildWrapper(entry, entrySource, options, encore);
      }

      encore.addEntry(entry.output, entrySource);
      seenEntries.add(entry.output);
      logEntry(entry.wrapper ? `entry+wrapper (${entry.wrapper.type})` : 'entry', entry);
    });
  });
}

function resolveSourcePath(source) {
  const absolutePath = path.resolve(process.cwd(), source);

  if (!fs.existsSync(absolutePath)) {
    // The manifest is generated by the PHP side (bundle discovery), which is
    // unreachable from the node toolchain — so a missing source usually means
    // a stale manifest, not a webpack problem.
    throw new Error(
      `[encore-manifest] Missing asset source ${absolutePath}. ` +
        `The manifest is probably stale (a package moved or removed this asset): ` +
        `regenerate it with \`php bin/console loader:generate-encore-manifest\` ` +
        `(run in the PHP container, or via .wex/bash/watch.sh which does it before watching).`
    );
  }

  return absolutePath;
}

function buildWrapper(entry, absoluteSource, options = {}, encore = Encore) {
  const wrapperContent = renderWrapperTemplate(
    toPosix(absoluteSource),
    entry.wrapper.className
  );
  const modulePath = buildWrapperVirtualPath(entry, options);
  pendingVirtualModules[modulePath] = wrapperContent;
  logPath('    wrapper (virtual)', modulePath, COLORS.gray);

  return modulePath;
}

function buildWrapperVirtualPath(entry, options) {
  const bundleDir = entry.bundle || 'app';
  const relativeDir = sanitizeRelativeDir(path.join(bundleDir, entry.relative || ''));
  const targetDir = path.join(options.virtualWrapperRoot || WRAPPER_VIRTUAL_ROOT, relativeDir);

  return path.join(targetDir, `${stringToKebabCase(buildWrapperBaseName(entry))}.js`);
}

function buildWrapperBaseName(entry) {
  if (entry.relative && entry.relative.length) {
    return path.basename(entry.relative);
  }

  return entry.output || 'index';
}

function finalizeVirtualModules(encore, options = {}) {
  const modules = pendingVirtualModules;
  pendingVirtualModules = {};

  if (!Object.keys(modules).length) {
    return;
  }

  virtualModulesInstance = new VirtualModules(modules);
  encore.addPlugin(virtualModulesInstance);
  logTitle('Virtual wrapper modules enabled', COLORS.green);
}

function sanitizeRelativeDir(relativePath = '') {
  if (!relativePath) {
    return '';
  }

  const dir = path.dirname(relativePath);
  return dir === '.' ? '' : dir;
}

function toPosix(filePath) {
  return filePath.split(path.sep).join('/');
}

function getWrapperTemplate() {
  if (!wrapperTemplateContent) {
    wrapperTemplateContent = fs.readFileSync(WRAPPER_TEMPLATE_PATH, 'utf8');
  }

  return wrapperTemplateContent;
}

function renderWrapperTemplate(classPath, className) {
  return getWrapperTemplate()
    .replace(/{classPath}/g, classPath)
    .replace(/{className}/g, className);
}

/** Read by the shell loop that runs the watcher. */
const ENTRY_LIST_CHANGED_EXIT_CODE = 75;

/**
 * How long a change is left to settle before it is believed. An editor saves by
 * writing a temporary file and renaming it, a checkout or an agent writes a
 * handful of files one after the other: read too early, the tree says something
 * it stops saying a moment later.
 */
const ENTRY_LIST_SETTLE_MS = 1200;

/**
 * What makes a file an entry — the rules of EncoreManifestBuilder, on the PHP
 * side, which writes the list webpack starts with. They are repeated here so a
 * file that could never be an entry — a helper under js/, a class, a partial —
 * does not stop the watch for nothing. A change to one is a change to both.
 *
 * Answers why the file is an entry, or null when it is not one.
 */
function describeEntrySource(relative) {
  const filename = path.posix.basename(relative);

  // Partials, and what an editor or a tool leaves behind for a moment.
  if (!filename || filename.startsWith('_') || filename.startsWith('.')) {
    return null;
  }

  const extension = path.posix.extname(filename).slice(1).toLowerCase();
  const firstSegment = relative.split('/')[0];
  // A class file is named with a capital: it is imported, never an entry of
  // its own, where it stands beside a page or a layout.
  const isClass = filename[0].toUpperCase() === filename[0];

  if (extension === 'scss' || extension === 'css') {
    return 'a stylesheet';
  }

  if (extension === 'vue') {
    return 'a vue component';
  }

  if (extension !== 'js' && extension !== 'ts') {
    return null;
  }

  if (firstSegment === 'layouts') {
    return isClass ? null : 'a layout script';
  }

  if (firstSegment === 'pages') {
    return isClass ? null : 'a page script';
  }

  if (firstSegment === 'components') {
    return 'a component script';
  }

  if (firstSegment === 'forms') {
    return 'a form script';
  }

  return null;
}

function realPathOrSelf(filePath) {
  try {
    return fs.realpathSync(filePath);
  } catch {
    return filePath;
  }
}

/** Every file under the roots that the rules make an entry, by real path. */
function collectEntrySources(roots) {
  const found = new Map();

  roots.forEach((root) => {
    const walk = (dir) => {
      let entries;

      try {
        entries = fs.readdirSync(dir, { withFileTypes: true });
      } catch {
        return;
      }

      for (const entry of entries) {
        if (entry.name.startsWith('.') || entry.name === 'node_modules') {
          continue;
        }

        const full = path.join(dir, entry.name);

        if (entry.isDirectory()) {
          walk(full);
          continue;
        }

        const relative = toPosix(path.relative(root, full));
        const reason = describeEntrySource(relative);

        if (reason) {
          found.set(full, { relative, reason });
        }
      }
    };

    walk(root);
  });

  return found;
}

/** The sources webpack was actually started with, by real path. */
function collectManifestSources(manifest) {
  const sources = new Set();
  const add = (entry) => {
    if (entry?.source) {
      sources.add(realPathOrSelf(path.resolve(process.cwd(), entry.source)));
    }
  };

  (manifest.entries?.css || []).forEach(add);
  Object.values(manifest.entries?.js || {}).forEach((entries) => (entries || []).forEach(add));

  return sources;
}

function waitFor(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Webpack settles its entries once, when it starts. A stylesheet, a script or a
 * vue created afterwards is therefore not compiled and not served, and nothing
 * says so: the page simply comes back without it, and the author concludes the
 * convention does not exist. This watches the directories the manifest was
 * built from and stops the watch when the entries they hold stop matching the
 * ones webpack was given, so the next start — which regenerates the list —
 * picks the change up.
 *
 * It stops for that and nothing else: a file the rules never make an entry
 * comes and goes freely, a file that was not an entry may go without anyone
 * minding, and a change is believed only once it has settled.
 *
 * Only in watch mode: a one-off build has no afterwards.
 */
class EntryListWatchdog {
  constructor(roots, manifestSources) {
    this.roots = roots;
    this.manifestSources = manifestSources;
    this.known = null;
  }

  apply(compiler) {
    // Webpack watches what it compiled, and a file nobody imports is outside
    // that: created, it would wake no one and be seen by no one. Declaring the
    // roots as context dependencies is what puts the directories themselves
    // under watch, so their contents changing is a reason to look again.
    compiler.hooks.afterCompile.tap('EntryListWatchdog', (compilation) => {
      this.roots.forEach((root) => compilation.contextDependencies.add(root));
    });

    compiler.hooks.watchRun.tapPromise('EntryListWatchdog', async () => {
      if (this.known === null) {
        this.known = collectEntrySources(this.roots);

        return;
      }

      if (!this.findChanges(collectEntrySources(this.roots)).length) {
        return;
      }

      // Read again once the tree has settled, and believed only then.
      await waitFor(ENTRY_LIST_SETTLE_MS);

      const current = collectEntrySources(this.roots);
      const changes = this.findChanges(current);

      if (!changes.length) {
        return;
      }

      logTitle('The list of entries is out of date', COLORS.magenta);
      changes.forEach(({ kind, file, reason }) => logPath(`  ${kind}`, `${file} (${reason})`));
      console.log(
        '\nWebpack was told its entries when it started and cannot be told '
        + 'again.\nStopping here so the next start compiles the list as it '
        + 'now stands.\n'
      );

      // A code of its own, so whoever runs the watch can tell this apart from
      // a build that died and restart rather than give up.
      process.exit(ENTRY_LIST_CHANGED_EXIT_CODE);
    });
  }

  // What changed that webpack cares about: an entry that appeared and is not
  // in its list, or one of its own sources that is gone — a file that was
  // never an entry leaves the list as it was.
  findChanges(current) {
    const changes = [];

    current.forEach(({ reason }, file) => {
      if (!this.known.has(file) && !this.manifestSources.has(file)) {
        changes.push({ kind: 'appeared', file, reason });
      }
    });

    this.known.forEach(({ reason }, file) => {
      if (!current.has(file) && this.manifestSources.has(file)) {
        changes.push({ kind: 'gone', file, reason });
      }
    });

    // What came and went without concerning webpack is taken as the new
    // state, so it is not weighed again at the next compilation.
    if (!changes.length) {
      this.known = current;
    }

    return changes;
  }
}

function watchEntryList(encore, manifest) {
  // By their real path, like the files found under them: a front reached
  // through a vendor link is the same directory as its source.
  const roots = (manifest.fronts || [])
    .map((front) => front.paths?.absolute)
    .filter((root) => root && fs.existsSync(root))
    .map(realPathOrSelf);

  if (!roots.length) {
    return;
  }

  // Registered whatever the mode: `watchRun` is a hook of the watcher and of
  // nothing else, so a build that runs once never reaches it — and asking
  // `process.argv` whether this is a watch is asking the wrong process, the
  // encore binary having rewritten it by the time the config is read.
  encore.addPlugin(new EntryListWatchdog(roots, collectManifestSources(manifest)));
}

function buildEncoreConfig(options = {}) {
  if (options.clearCache !== false) {
    execSync('php bin/console cache:clear --no-warmup', {stdio: 'inherit'});
  }

  maybeGenerateEncoreManifest(options);
  configureEncoreBase(options);
  applyManifestEntries(options);
  watchEntryList(Encore, loadManifest());

  const config = Encore.getWebpackConfig();

  // Resolve: symlinks false + extensionAlias for .js→.ts in symlinked @wexample packages.
  config.resolve = {
    ...(config.resolve || {}),
    symlinks: false,
    // Scripts first. A component keeps its script and its vue twin in one
    // directory under one name, so `./button-input` has two candidates; the
    // bare path means the script, and a vue file is always imported as `.vue`.
    extensions: Array.from(new Set(['.ts', '.tsx', '.js', ...(config.resolve?.extensions || [])])),
    extensionAlias: {
      ...(config.resolve?.extensionAlias || {}),
      '.js': ['.ts', '.tsx', '.js'],
      '.mjs': ['.mts', '.mjs'],
      '.cjs': ['.cts', '.cjs'],
    },
    alias: {
      ...(config.resolve?.alias || {}),
      // Consumed by RoutingService.ts — avoids the duplicate-singleton bug from InjectPlugin.
      '@fosRoutes': path.resolve(process.cwd(), 'var/cache/fosRoutes.json'),
      ...(options.alias || {}),
    },
  };
  // The `@wexample/<php package>` aliases come from the manifest and point at
  // `vendor/<package>/assets` — the live tree — and the tsconfig `paths` say the
  // same, so whatever yarn put under node_modules/@wexample/ for those packages
  // is never read by this build. Never, but for one case: a file a `paths`
  // entry maps to that does not exist makes TypeScript fall back to node
  // resolution, and if the app declared the package as `file:` (a copy) rather
  // than `link:` (a symlink), the fallback type-checks a frozen copy of the
  // whole package and reports errors in files nobody touched. The rule and the
  // reasoning: symfony-design-system knowledge, contributing/assets-as-npm-package.

  // Remove FosRouting InjectPlugin (duplicate singleton bug). Routes are loaded via @fosRoutes alias.
  const fosRoutingIndex = config.plugins.findIndex(
    (p) => p.constructor && p.constructor.name === 'FosRouting'
  );
  if (fosRoutingIndex !== -1) {
    config.plugins.splice(fosRoutingIndex, 1);
  }

  // ts-loader: allow processing of @wexample/* packages shipped as TypeScript source.
  config.module.rules.forEach((rule) => {
    if (!rule.exclude) return;
    const uses = Array.isArray(rule.use) ? rule.use : rule.use ? [rule.use] : [];
    const hasTsLoader = uses.some(
      (u) =>
        (typeof u === 'string' && u.includes('ts-loader')) ||
        (typeof u === 'object' && u?.loader?.includes('ts-loader'))
    );
    if (hasTsLoader) {
      rule.exclude = /node_modules\/(?!@wexample\/)/;
      uses.forEach((u) => {
        if (typeof u === 'object' && u?.loader?.includes('ts-loader')) {
          u.options = { ...(u.options || {}), allowTsInNodeModules: true };
        }
      });
    }
  });

  // Persistent build cache: enabled in production by default, disabled in dev to avoid
  // stale bundles (e.g. fosRoutes.json updates not picked up). Override with { buildCache: true/false }.
  const enableCache = options.buildCache ?? Encore.isProduction();
  if (enableCache && !config.cache?.type) {
    config.cache = {
      type: 'filesystem',
      buildDependencies: {
        config: [
          fileURLToPath(import.meta.url),
          ...(fs.existsSync(DEFAULT_MANIFEST_PATH) ? [DEFAULT_MANIFEST_PATH] : []),
        ],
      },
    };
  }

  return config;
}

